const supported = new Set(["en", "ps-Arab-PK"]);
let activeLocale = "en";
export function initialInterfaceLocale() {
  const requested = new URL(location.href).searchParams.get("lang");
  return supported.has(requested) ? requested : (supported.has(document.documentElement.lang) ? document.documentElement.lang : "en");
}
export function interfaceText(key, values = {}) {
  let result = interfaceMessages[key][activeLocale];
  for (const [name, value] of Object.entries(values)) result = result.replaceAll(`{${name}}`, String(value));
  return result;
}
export function applyInterfaceLocale(locale) {
  activeLocale = supported.has(locale) ? locale : "en";
  document.documentElement.lang = activeLocale;
  document.documentElement.dir = activeLocale === "ps-Arab-PK" ? "rtl" : "ltr";
  for (const element of document.querySelectorAll("[data-ui]")) {
    const record = interfaceMessages[element.dataset.ui];
    if (record.html) element.innerHTML = record[activeLocale];
    else element.textContent = record[activeLocale];
  }
  for (const attr of ["aria-label", "placeholder", "content"]) {
    for (const element of document.querySelectorAll(`[data-ui-${attr}]`)) {
      element.setAttribute(attr, interfaceText(element.getAttribute(`data-ui-${attr}`)));
    }
  }
  document.querySelector("#interface-language").value = activeLocale;
  const fallback = document.querySelector("#catalogue-fallback-link");
  if (fallback) fallback.href = activeLocale === "ps-Arab-PK" ? "evidence/PASHTO632_REVIEW.ps.html" : "README.md#read-or-inspect-an-edition";
  return activeLocale;
}
